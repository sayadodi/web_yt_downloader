import { spawn } from "node:child_process";
import { access, chmod, writeFile } from "node:fs/promises";
import { existsSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import ffmpegStatic from "ffmpeg-static";

const IS_WINDOWS = process.platform === "win32";
const BIN_DIR = path.join(process.cwd(), "bin");
const COOKIES_TMP_PATH = path.join(os.tmpdir(), "ytaudio-cookies.txt");

export const YTDLP_PATH = path.join(
  BIN_DIR,
  IS_WINDOWS ? "yt-dlp.exe" : "yt-dlp",
);
export function resolveFfmpegPath(): string {
  const localBin = path.join(BIN_DIR, IS_WINDOWS ? "ffmpeg.exe" : "ffmpeg");
  if (existsSync(localBin)) return localBin;

  if (typeof ffmpegStatic === "string" && existsSync(ffmpegStatic)) {
    return ffmpegStatic;
  }
  return "";
}

export const FFMPEG_PATH = resolveFfmpegPath();


export class YtdlpError extends Error {
  code: string;
  stderr: string;

  constructor(message: string, code: string, stderr = "") {
    super(message);
    this.name = "YtdlpError";
    this.code = code;
    this.stderr = stderr;
  }
}

export type CookieStatus = {
  active: boolean;
  count: number;
  hasLogin: boolean;
  path: string | null;
};

let prepared: Promise<void> | null = null;
let activeCookiesPath: string | null = null;
let cachedCookieStatus: CookieStatus | null = null;

export function normalizeNetscapeCookies(rawText: string): {
  content: string;
  count: number;
  hasLogin: boolean;
} {
  let trimmed = rawText.trim();
  if (!trimmed) return { content: "", count: 0, hasLogin: false };

  // Strip wrapping quotes if user pasted with quotes
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    trimmed = trimmed.slice(1, -1).trim();
  }

  const validLines: string[] = [
    "# Netscape HTTP Cookie File",
    "# http://curl.haxx.se/rfc/cookie_spec.html",
    "# This file was generated by yt-audio",
    "",
  ];
  let count = 0;
  let hasLogin = false;

  const checkLogin = (name: string) => {
    const n = name.toUpperCase();
    if (
      n === "LOGIN_INFO" ||
      n === "SAPISID" ||
      n === "APISID" ||
      n === "SSID" ||
      n.includes("SECURE-1PSID") ||
      n.includes("SECURE-3PSID")
    ) {
      hasLogin = true;
    }
  };

  // 1. JSON format (from Cookie-Editor, EditThisCookie, etc.)
  if (trimmed.startsWith("[") && trimmed.endsWith("]")) {
    try {
      const arr = JSON.parse(trimmed) as Array<Record<string, unknown>>;
      for (const item of arr) {
        const name = String(item.name || "").trim();
        const value = String(item.value || "").trim();
        if (!name) continue;

        checkLogin(name);

        let domain = String(item.domain || ".youtube.com").trim();
        if (!domain.startsWith(".") && domain.includes(".")) domain = "." + domain;
        const domSpec = domain.startsWith(".") ? "TRUE" : "FALSE";
        const cookiePath = String(item.path || "/").trim();
        const secure = item.secure === false ? "FALSE" : "TRUE";
        const rawExp = Number(item.expirationDate || item.expires || 0);
        const expires =
          rawExp > 0 ? Math.floor(rawExp) : Math.floor(Date.now() / 1000 + 86400 * 365);

        validLines.push(
          [domain, domSpec, cookiePath, secure, expires, name, value].join("\t"),
        );
        count++;
      }
      return { content: validLines.join("\n") + "\n", count, hasLogin };
    } catch {
      // fallback to line parsing
    }
  }

  // 2. Line-by-line format (tab or space-delimited from Vercel inputs)
  const lines = trimmed.replace(/\\n/g, "\n").split(/\r?\n/);
  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    if (line.includes("\t")) {
      const parts = line.split("\t");
      if (parts.length >= 7) {
        checkLogin(parts[5]);
        validLines.push(parts.slice(0, 7).join("\t"));
        count++;
      }
    } else {
      // Space-delimited: domain, flag, path, secure, expiration, name, value
      const parts = line.split(/\s+/);
      if (parts.length >= 7) {
        const domain = parts[0];
        const domSpec = parts[1].toUpperCase() === "FALSE" ? "FALSE" : "TRUE";
        const cookiePath = parts[2] || "/";
        const secure = parts[3].toUpperCase() === "FALSE" ? "FALSE" : "TRUE";
        const expires = parts[4] || "0";
        const name = parts[5];
        const value = parts.slice(6).join(" ");
        checkLogin(name);
        validLines.push(
          [domain, domSpec, cookiePath, secure, expires, name, value].join("\t"),
        );
        count++;
      }
    }
  }

  return { content: validLines.join("\n") + "\n", count, hasLogin };
}

export function getCookieStatus(): CookieStatus {
  if (cachedCookieStatus) return cachedCookieStatus;
  resolveCookiesFile();
  return (
    cachedCookieStatus || {
      active: false,
      count: 0,
      hasLogin: false,
      path: null,
    }
  );
}

export function resolveCookiesFile(): string | null {
  if (cachedCookieStatus?.active && cachedCookieStatus.path && existsSync(cachedCookieStatus.path)) {
    return cachedCookieStatus.path;
  }

  const rawCookies = process.env.YOUTUBE_COOKIES?.trim();
  const base64Cookies = process.env.YOUTUBE_COOKIES_BASE64?.trim();

  let cookiesText = "";
  if (rawCookies) {
    cookiesText = rawCookies;
  } else if (base64Cookies) {
    try {
      cookiesText = Buffer.from(base64Cookies, "base64").toString("utf-8");
    } catch (err) {
      console.error("[ytdlp] Gagal mendekode YOUTUBE_COOKIES_BASE64:", err);
    }
  }

  if (cookiesText && cookiesText.length > 10) {
    const { content, count, hasLogin } = normalizeNetscapeCookies(cookiesText);
    if (count > 0) {
      try {
        writeFileSync(COOKIES_TMP_PATH, content, "utf-8");
        activeCookiesPath = COOKIES_TMP_PATH;
        cachedCookieStatus = {
          active: true,
          count,
          hasLogin,
          path: COOKIES_TMP_PATH,
        };
        return COOKIES_TMP_PATH;
      } catch (err) {
        console.error("[ytdlp] Gagal menulis cookies ke COOKIES_TMP_PATH:", err);
      }
    } else {
      console.warn("[ytdlp] YOUTUBE_COOKIES ada tetapi tidak ada baris cookie yang valid");
      cachedCookieStatus = {
        active: false,
        count: 0,
        hasLogin: false,
        path: null,
      };
    }
  }

  const customCookieFile = process.env.YTDLP_COOKIES_FILE?.trim();
  if (customCookieFile && existsSync(path.resolve(customCookieFile))) {
    activeCookiesPath = path.resolve(customCookieFile);
    cachedCookieStatus = { active: true, count: 1, hasLogin: true, path: activeCookiesPath };
    return activeCookiesPath;
  }

  const localCookies = path.join(process.cwd(), "cookies.txt");
  if (existsSync(localCookies)) {
    activeCookiesPath = localCookies;
    cachedCookieStatus = { active: true, count: 1, hasLogin: true, path: localCookies };
    return localCookies;
  }

  cachedCookieStatus = { active: false, count: 0, hasLogin: false, path: null };
  return null;
}

export function prepare(): Promise<void> {
  if (!prepared) {
    prepared = (async () => {
      try {
        await access(YTDLP_PATH);
      } catch {
        throw new YtdlpError(
          "Binary yt-dlp tidak ditemukan. Jalankan `npm run fetch:bin`.",
          "BINARY_MISSING",
        );
      }

      // Check and resolve cookies
      resolveCookiesFile();

      if (IS_WINDOWS) return;
      // Lambda zip archives occasionally lose the executable bit.
      await chmod(YTDLP_PATH, 0o755).catch(() => {});
      const ffmpeg = resolveFfmpegPath();
      if (ffmpeg) await chmod(ffmpeg, 0o755).catch(() => {});
    })();
  }
  return prepared;
}

/** Shared flags. `--no-playlist` guarantees a single audio file per request. */
export function ytdlpBaseArgs(): string[] {
  const args = [
    "--no-playlist",
    "--no-warnings",
    "--no-cache-dir",
    "--socket-timeout",
    "20",
    "--retries",
    "3",
    "--js-runtimes",
    `node:${process.execPath}`,
    "--remote-components",
    "ejs:github",
  ];

  const cookiePath = resolveCookiesFile();
  if (cookiePath) {
    args.push("--cookies", cookiePath);
  }

  const customClients = process.env.YTDLP_PLAYER_CLIENTS?.trim();
  if (customClients) {
    args.push("--extractor-args", `youtube:player_client=${customClients}`);
  }

  const ffmpeg = resolveFfmpegPath();
  if (ffmpeg) args.push("--ffmpeg-location", ffmpeg);

  return args;
}

export type RunOptions = {
  signal?: AbortSignal;
  timeoutMs?: number;
  onStdoutLine?: (line: string) => void;
};

export type RunResult = {
  stdout: string;
  stderr: string;
  code: number;
};

export function getYtdlpEnv(): NodeJS.ProcessEnv {
  const nodeDir = path.dirname(process.execPath);
  const existingPath = process.env.PATH || "";
  const combinedPath = existingPath.includes(nodeDir)
    ? existingPath
    : `${nodeDir}${path.delimiter}${existingPath}`;

  return {
    ...process.env,
    PATH: combinedPath,
    // Keep yt-dlp from writing outside the ephemeral filesystem.
    HOME: os.tmpdir(),
    XDG_CACHE_HOME: path.join(os.tmpdir(), "yt-dlp-cache"),
    PYTHONIOENCODING: "utf-8",
  };
}

export async function runYtdlp(
  args: string[],
  options: RunOptions = {},
): Promise<RunResult> {
  await prepare();

  return new Promise<RunResult>((resolve, reject) => {
    const child = spawn(YTDLP_PATH, args, {
      env: getYtdlpEnv(),
      windowsHide: true,
    });

    let stdout = "";
    let stderr = "";
    let lineBuffer = "";
    let settled = false;
    let timer: ReturnType<typeof setTimeout> | undefined;

    const finish = (action: () => void) => {
      if (settled) return;
      settled = true;
      if (timer) clearTimeout(timer);
      options.signal?.removeEventListener("abort", onAbort);
      action();
    };

    const onAbort = () => {
      child.kill("SIGKILL");
      finish(() =>
        reject(new YtdlpError("Permintaan dibatalkan.", "ABORTED", stderr)),
      );
    };

    if (options.signal) {
      if (options.signal.aborted) {
        onAbort();
        return;
      }
      options.signal.addEventListener("abort", onAbort, { once: true });
    }

    if (options.timeoutMs) {
      timer = setTimeout(() => {
        child.kill("SIGKILL");
        finish(() =>
          reject(
            new YtdlpError(
              "Proses melebihi batas waktu server.",
              "TIMEOUT",
              stderr,
            ),
          ),
        );
      }, options.timeoutMs);
    }

    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk: string) => {
      if (stdout.length < 4_000_000) stdout += chunk;

      if (options.onStdoutLine) {
        lineBuffer += chunk;
        const lines = lineBuffer.split(/\r?\n/);
        lineBuffer = lines.pop() ?? "";
        for (const line of lines) {
          if (line.trim()) options.onStdoutLine(line);
        }
      }
    });

    child.stderr.setEncoding("utf8");
    child.stderr.on("data", (chunk: string) => {
      if (stderr.length < 200_000) stderr += chunk;
    });

    child.on("error", (error) => {
      finish(() =>
        reject(
          new YtdlpError(
            `Tidak bisa menjalankan yt-dlp: ${error.message}`,
            "SPAWN_FAILED",
          ),
        ),
      );
    });

    child.on("close", (code) => {
      finish(() => resolve({ stdout, stderr, code: code ?? -1 }));
    });
  });
}

export type RawVideoInfo = {
  id?: string;
  title?: string;
  uploader?: string;
  channel?: string;
  duration?: number;
  thumbnail?: string;
  abr?: number;
  is_live?: boolean;
  live_status?: string;
};

export async function fetchRawInfo(
  url: string,
  signal?: AbortSignal,
): Promise<RawVideoInfo> {
  const { stdout, stderr, code } = await runYtdlp(
    [
      "-J",
      "--skip-download",
      "--no-check-formats",
      ...ytdlpBaseArgs(),
      url,
    ],
    { signal, timeoutMs: 45_000 },
  );

  if (code !== 0) {
    throw new YtdlpError("Gagal mengambil metadata video.", "INFO_FAILED", stderr);
  }

  try {
    return JSON.parse(stdout) as RawVideoInfo;
  } catch {
    throw new YtdlpError(
      "Gagal membaca metadata video.",
      "INFO_PARSE_FAILED",
      stderr,
    );
  }
}
